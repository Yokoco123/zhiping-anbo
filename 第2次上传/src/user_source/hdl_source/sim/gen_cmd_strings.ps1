# 【自动字号】每条最多 511 字节，按 512 字节一条存（tb 里 strs[k * 512 + i]）
$utf8 = New-Object System.Text.UTF8Encoding($false)
$sb = New-Object System.Text.StringBuilder
for ($k = 0; $k -lt $S.Count; $k++) {
    $b = $utf8.GetBytes($S[$k])
    if ($b.Length -gt 511) { throw "string $k is $($b.Length) bytes" }
    for ($i = 0; $i -lt 512; $i++) { [void]$sb.Append($(if ($i -lt $b.Length) { $b[$i].ToString('X2') } else { '00' })).Append("`n") }
}
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'cmd_strings.hex'), $sb.ToString())
Write-Host "OK: $($S.Count) strings"
