# gen_cmd.ps1 - cmd.txt (PIN, command keywords, reply texts) -> ../cmd_rom.v
# All strings are stored as UTF-8 bytes in one 4096 x 8 ROM (BRAM32K x1):
#   id 0         = PIN
#   id 1  .. 24  = keywords incl. notice-board ones (KW_QP .. KW_QDEL) and KW_AUTOON KW_AUTOOFF KW_MUTE
#   id 25 .. 28  = emergency types, 29 .. 35 = emergency default texts
#   id 36 .. 72  = replies (RP_*), each followed by CR LF and a 0 terminator (the UART sender stops at 0)
#   id 73 .. 81  = notice-list pieces (LS_*), followed by a 0 only; "\n" in the text = CR LF
#   id 82 .. 85  = more replies (RP_*)
#   id 86        = keyword KW_PHOTO (serial_cmd tries it after KW_MUTE), 87 .. 90 = photo replies (RP_PH_*)
#   id 91        = keyword KW_SUB (tried after KW_PHOTO), 92 .. 95 = custom subtitle replies (RP_SUB_*)
#   id 96 .. 99  = keywords KW_WAVEON KW_WAVEOFF KW_RESON KW_RESOFF (tried after KW_SUB), 100 .. 103 = their replies
# A table gives start / length for every id.
$InFile  = Join-Path $PSScriptRoot 'cmd.txt'
$OutFile = Join-Path (Split-Path $PSScriptRoot -Parent) 'cmd_rom.v'
$Ids = @('PIN',
         'KW_NOTICE', 'KW_CLEAR', 'KW_SUBON', 'KW_SUBOFF', 'KW_MUSON', 'KW_MUSOFF', 'KW_NEXT', 'KW_PREV', 'KW_HELP', 'KW_FONT',
         'KW_ALM1', 'KW_ALM2', 'KW_ALM3', 'KW_ALMCLR',
         'KW_QP', 'KW_QT', 'KW_QF', 'KW_QF2', 'KW_QLIST', 'KW_QDALL', 'KW_QDEL', 'KW_AUTOON', 'KW_AUTOOFF', 'KW_MUTE',
         'TY_FIRE', 'TY_QUAKE', 'TY_SECU', 'TY_FAULT',
         'TP_FIRE', 'TP_QUAKE', 'TP_SECU', 'TP_FAULT', 'TP_L1', 'TP_L2', 'TP_L3',
         'RP_OK_NOTICE', 'RP_OK_TRUNC', 'RP_OK_CLEAR', 'RP_OK_SUBON', 'RP_OK_SUBOFF', 'RP_OK_MUSON', 'RP_OK_MUSOFF',
         'RP_OK_NEXT', 'RP_OK_PREV', 'RP_HELP', 'RP_ERR_PIN', 'RP_ERR_UNKNOWN', 'RP_ERR_EMPTY', 'RP_ERR_NOFONT',
         'RP_ERR_FLASH', 'RP_ERR_EMERG', 'RP_FONT_READY', 'RP_FONT_OK', 'RP_FONT_BAD', 'RP_FONT_BROKEN',
         'RP_OK_ALM1', 'RP_OK_ALM2', 'RP_OK_ALM3', 'RP_OK_ALMCLR', 'RP_OK_ALMSW1', 'RP_OK_ALMNOTXT',
         'RP_OK_Q1', 'RP_OK_Q2', 'RP_OK_Q3', 'RP_OK_Q4', 'RP_OK_QLONG', 'RP_ERR_QFULL', 'RP_OK_QDEL', 'RP_OK_QDALL',
         'RP_ERR_QNONE', 'RP_ERR_QSAVE', 'RP_LS_HEAD',
         'LS_N1', 'LS_N2', 'LS_N3', 'LS_N4', 'LS_T1', 'LS_T2', 'LS_T3', 'LS_EMPTY', 'LS_EOL',
         'RP_OK_AUTOON', 'RP_OK_AUTOOFF', 'RP_OK_MUTE', 'RP_ERR_NOALM',
         'KW_PHOTO', 'RP_PH_READY', 'RP_PH_OK', 'RP_PH_BAD', 'RP_PH_BROKEN',
         'KW_SUB', 'RP_SUB_OK', 'RP_SUB_LONG', 'RP_SUB_DEF', 'RP_SUB_BADN',
         'KW_WAVEON', 'KW_WAVEOFF', 'KW_RESON', 'KW_RESOFF',
         'RP_OK_WAVEON', 'RP_OK_WAVEOFF', 'RP_OK_RESON', 'RP_OK_RESOFF')
$Depth = 4096

if (-not (Test-Path $InFile)) { Write-Host "ERROR: $InFile not found"; exit 1 }
$texts = @{}
foreach ($line in [IO.File]::ReadAllLines($InFile, [Text.Encoding]::UTF8)) {
    $t = $line.Trim()
    if ($t -eq '' -or $t.StartsWith('#')) { continue }
    $eq = $t.IndexOf('=')
    if ($eq -lt 1) { Write-Host "WARNING: skipped line: $t"; continue }
    $texts[$t.Substring(0, $eq).Trim().ToUpper()] = $t.Substring($eq + 1).Trim()
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
$bytes = New-Object System.Collections.Generic.List[byte]
$tab = New-Object System.Text.StringBuilder
$hdr = New-Object System.Text.StringBuilder
for ($id = 0; $id -lt $Ids.Count; $id++) {
    $k = $Ids[$id]
    if (-not $texts.ContainsKey($k) -or $texts[$k] -eq '') { Write-Host "ERROR: $k missing or empty in cmd.txt"; exit 1 }
    $tx = $texts[$k]
    if ($k.StartsWith('LS_')) { $tx = $tx.Replace('\n', "`r`n") }
    $b = $utf8.GetBytes($tx)
    if ($k -eq 'PIN' -and ($b.Length -lt 1 -or $b.Length -gt 16)) { Write-Host 'ERROR: PIN must be 1..16 characters'; exit 1 }
    if ($k -eq 'PIN' -and $texts[$k].Contains(' ')) { Write-Host 'ERROR: PIN must not contain spaces'; exit 1 }
    $start = $bytes.Count
    $bytes.AddRange([byte[]]$b)
    $len = $b.Length
    if ($k.StartsWith('RP_')) { $bytes.Add(13); $bytes.Add(10); $bytes.Add(0) }
    if ($k.StartsWith('LS_')) { $bytes.Add(0) }
    $tl = [Math]::Min($len, 255)                 # replies are sent up to the 0, their length is not used
    [void]$tab.AppendLine(("            7'd{0}: begin s_start = 12'd{1}; s_len = 8'd{2}; end" -f $id, $start, $tl))
    [void]$hdr.AppendLine(("//   id {0,2} {1,-15} start {2,4} len {3,3}  {4}" -f $id, $k, $start, $len, $texts[$k]))
    if ($len -gt 255 -and -not $k.StartsWith('RP_')) { Write-Host "ERROR: $k is $len bytes, max 255"; exit 1 }
}
if ($bytes.Count -gt $Depth) { Write-Host "ERROR: $($bytes.Count) bytes in total, more than $Depth - shorten the replies"; exit 1 }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('`timescale 1ns/1ps')
[void]$sb.AppendLine('// -----------------------------------------------------------------------------')
[void]$sb.AppendLine('// AUTO-GENERATED by subtitle/gen_cmd.ps1 from subtitle/cmd.txt -- do not edit by hand')
[void]$sb.AppendLine("// generated $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
[void]$sb.AppendLine("// Serial command strings, UTF-8. $($bytes.Count) of $Depth bytes used. Replies end with CR LF 0.")
[void]$sb.Append($hdr.ToString())
[void]$sb.AppendLine('// -----------------------------------------------------------------------------')
[void]$sb.AppendLine('module cmd_rom (')
[void]$sb.AppendLine('    input  wire       clk,')
[void]$sb.AppendLine('    input  wire [11:0] addr_a,          // two read ports (keyword compare / reply sender), 1-clock latency')
[void]$sb.AppendLine('    output reg  [7:0] data_a,')
[void]$sb.AppendLine('    input  wire [11:0] addr_b,')
[void]$sb.AppendLine('    output reg  [7:0] data_b,')
[void]$sb.AppendLine('    input  wire [6:0] sid,')
[void]$sb.AppendLine('    output reg  [11:0] s_start,')
[void]$sb.AppendLine('    output reg  [7:0] s_len')
[void]$sb.AppendLine(');')
[void]$sb.AppendLine("    reg [7:0] mem [0:$($Depth - 1)] /* fehdl force_ram=1, ram_style=""bram_32k"" */;")
[void]$sb.AppendLine('    integer i;')
[void]$sb.AppendLine('    initial begin')
[void]$sb.AppendLine("        for (i = 0; i < $Depth; i = i + 1)")
[void]$sb.AppendLine("            mem[i] = 8'h00;")
for ($i = 0; $i -lt $bytes.Count; $i++) {
    if ($bytes[$i] -ne 0) { [void]$sb.AppendLine(('        mem[{0}] = 8''h{1:X2};' -f $i, $bytes[$i])) }
}
[void]$sb.AppendLine('    end')
[void]$sb.AppendLine('    always @(posedge clk) begin')
[void]$sb.AppendLine('        data_a <= mem[addr_a];')
[void]$sb.AppendLine('        data_b <= mem[addr_b];')
[void]$sb.AppendLine('    end')
[void]$sb.AppendLine('    always @(*) begin')
[void]$sb.AppendLine('        case (sid)')
[void]$sb.Append($tab.ToString())
[void]$sb.AppendLine("            default: begin s_start = 12'd0; s_len = 8'd0; end")
[void]$sb.AppendLine('        endcase')
[void]$sb.AppendLine('    end')
[void]$sb.AppendLine('endmodule')
[IO.File]::WriteAllText($OutFile, $sb.ToString(), $utf8)
Write-Host "OK: wrote $OutFile ($($bytes.Count) bytes)"
