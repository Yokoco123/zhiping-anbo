# gen_subtitle.ps1 - render subtitles.txt (SimSun 16px bitmap font) into ../subtitle_rom.v
# Each subtitle becomes a strip of 16-bit columns (bit 0 = top row). Slot order:
#   0..3 = PIC1..PIC4, 4 = EMERG, 5 = NOTICE (reserved for UART notices)
# No font is stored in the FPGA: any character Windows can draw can be shown.
Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName System.Windows.Forms

$SlotNames = @('PIC1', 'PIC2', 'PIC3', 'PIC4', 'EMERG', 'NOTICE')
$MaxCols   = 1024
$GapCols   = 48
$Height    = 16
$InFile    = Join-Path $PSScriptRoot 'subtitles.txt'
$OutFile   = Join-Path (Split-Path $PSScriptRoot -Parent) 'subtitle_rom.v'

$font  = New-Object System.Drawing.Font('SimSun', 16, [System.Drawing.GraphicsUnit]::Pixel)
$flags = [System.Windows.Forms.TextFormatFlags]::NoPadding -bor
         [System.Windows.Forms.TextFormatFlags]::NoPrefix -bor
         [System.Windows.Forms.TextFormatFlags]::SingleLine

function Render-Text([string]$text) {
    $cols = New-Object System.Collections.Generic.List[int]
    if ([string]::IsNullOrEmpty($text)) { return ,$cols }
    $sz  = [System.Windows.Forms.TextRenderer]::MeasureText($text, $font, (New-Object System.Drawing.Size(60000, 40)), $flags)
    $bmp = New-Object System.Drawing.Bitmap($sz.Width, 24)
    $g   = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::White)
    [System.Windows.Forms.TextRenderer]::DrawText($g, $text, $font, (New-Object System.Drawing.Point(0, 0)),
        [System.Drawing.Color]::Black, [System.Drawing.Color]::White, $flags)
    $g.Dispose()
    for ($x = 0; $x -lt $sz.Width; $x++) {
        $w = 0
        for ($y = 0; $y -lt $Height; $y++) {
            if ($bmp.GetPixel($x, $y).R -lt 128) { $w = $w -bor (1 -shl $y) }
        }
        $cols.Add($w)
    }
    $bmp.Dispose()
    return ,$cols
}

if (-not (Test-Path $InFile)) { Write-Host "ERROR: $InFile not found"; exit 1 }
$texts = @{}
foreach ($line in [IO.File]::ReadAllLines($InFile, [Text.Encoding]::UTF8)) {
    $t = $line.Trim()
    if ($t -eq '' -or $t.StartsWith('#')) { continue }
    $eq = $t.IndexOf('=')
    if ($eq -lt 1) { Write-Host "WARNING: skipped line: $t"; continue }
    $texts[$t.Substring(0, $eq).Trim().ToUpper()] = $t.Substring($eq + 1)
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('`timescale 1ns/1ps')
[void]$sb.AppendLine('// -----------------------------------------------------------------------------')
[void]$sb.AppendLine('// AUTO-GENERATED by subtitle/gen_subtitle.ps1 from subtitle/subtitles.txt -- do not edit by hand')
[void]$sb.AppendLine("// generated $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
[void]$sb.AppendLine('// Subtitle strips: SimSun 16px, one 16-bit word per column, bit 0 = top row.')
[void]$sb.AppendLine("// 6 slots x $MaxCols columns, address = {slot[2:0], col[9:0]}")
$lens = @()
$body = New-Object System.Text.StringBuilder
for ($s = 0; $s -lt $SlotNames.Count; $s++) {
    $name = $SlotNames[$s]
    $raw  = if ($texts.ContainsKey($name)) { $texts[$name] } else { '' }
    $sep  = $raw.IndexOfAny([char[]]@('|', [char]0xFF5C))
    if ($sep -ge 0) { $cn = $raw.Substring(0, $sep).Trim(); $en = $raw.Substring($sep + 1).Trim() }
    else            { $cn = $raw.Trim(); $en = '' }
    $a = Render-Text $cn
    $b = Render-Text $en
    $cols = New-Object System.Collections.Generic.List[int]
    $cols.AddRange($a)
    if ($a.Count -gt 0 -and $b.Count -gt 0) { for ($i = 0; $i -lt $GapCols; $i++) { $cols.Add(0) } }
    $cols.AddRange($b)
    if ($cols.Count -gt $MaxCols) {
        Write-Host "WARNING: $name is $($cols.Count) columns, truncated to $MaxCols"
        $cols.RemoveRange($MaxCols, $cols.Count - $MaxCols)
    }
    $lens += $cols.Count
    [void]$sb.AppendLine("//   slot $s $name ($($cols.Count) cols): $cn | $en")
    [void]$body.AppendLine("        // slot $s $name")
    for ($i = 0; $i -lt $cols.Count; $i++) {
        if ($cols[$i] -ne 0) {
            [void]$body.AppendLine(('        mem[{0}] = 16''h{1:X4};' -f ($s * $MaxCols + $i), $cols[$i]))
        }
    }
    Write-Host ("{0,-6} {1,4} cols  {2} | {3}" -f $name, $cols.Count, $cn, $en)
}
[void]$sb.AppendLine('// -----------------------------------------------------------------------------')
[void]$sb.AppendLine('module subtitle_rom (')
[void]$sb.AppendLine('    input  wire        clk,')
[void]$sb.AppendLine('    input  wire [12:0] raddr,')
[void]$sb.AppendLine('    output reg  [15:0] rdata,')
[void]$sb.AppendLine('    output wire [10:0] len0, len1, len2, len3, len4, len5')
[void]$sb.AppendLine(');')
[void]$sb.AppendLine('    reg [15:0] mem [0:6143] /* fehdl force_ram=1, ram_style="bram" */;')
[void]$sb.AppendLine('    integer i;')
[void]$sb.AppendLine('    initial begin')
[void]$sb.AppendLine('        for (i = 0; i < 6144; i = i + 1)')
[void]$sb.AppendLine("            mem[i] = 16'h0000;")
[void]$sb.Append($body.ToString())
[void]$sb.AppendLine('    end')
[void]$sb.AppendLine('    always @(posedge clk)')
[void]$sb.AppendLine('        rdata <= mem[raddr];')
for ($s = 0; $s -lt $SlotNames.Count; $s++) {
    [void]$sb.AppendLine(("    assign len{0} = 11'd{1};" -f $s, $lens[$s]))
}
[void]$sb.AppendLine('endmodule')
[IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "OK: wrote $OutFile"
