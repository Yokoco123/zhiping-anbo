# gen_page.ps1 - render page.txt into ../page_rom.v (notice-board page: titles, footers, digits)
# Same column format as gen_splash.ps1: one 16-bit word per column, bit 0 = top row.
#   T_PERSON / T_THING / T_FOUND : Microsoft YaHei Bold 44px in a 48-row box, stored as 3 bands
#                                  (rows 0-15, 16-31, 32-47) back to back: band k starts at t_s0 + k * t_w
#   DIGITS : "0123456789/" in fixed 8-column cells (SimSun 16px, shown x2 on the page)
#   F_PERSON / F_THING / F_FOUND : footer line of each kind of notice, SimSun 16px, centred
# ROM is 4096 x 16 (two BRAM32K); the script stops with an error if the text does not fit.
Add-Type -AssemblyName System.Drawing
Add-Type -AssemblyName System.Windows.Forms

$InFile  = Join-Path $PSScriptRoot 'page.txt'
$OutFile = Join-Path (Split-Path $PSScriptRoot -Parent) 'page_rom.v'
$Depth   = 4096

$small = New-Object System.Drawing.Font('SimSun', 16, [System.Drawing.GraphicsUnit]::Pixel)
$big   = New-Object System.Drawing.Font('Microsoft YaHei', 44, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
$flags = [System.Windows.Forms.TextFormatFlags]::NoPadding -bor
         [System.Windows.Forms.TextFormatFlags]::NoPrefix -bor
         [System.Windows.Forms.TextFormatFlags]::SingleLine

function Get-Cols($bmp, [int]$x0, [int]$w, [int]$y0) {
    $cols = New-Object System.Collections.Generic.List[int]
    for ($x = $x0; $x -lt $x0 + $w; $x++) {
        $v = 0
        for ($r = 0; $r -lt 16; $r++) {
            $y = $y0 + $r
            if ($x -ge 0 -and $x -lt $bmp.Width -and $y -ge 0 -and $y -lt $bmp.Height -and $bmp.GetPixel($x, $y).R -lt 128) {
                $v = $v -bor (1 -shl $r)
            }
        }
        $cols.Add($v)
    }
    return ,$cols
}

function Render-Small([string]$text) {
    if ([string]::IsNullOrEmpty($text)) { return ,(New-Object System.Collections.Generic.List[int]) }
    $sz  = [System.Windows.Forms.TextRenderer]::MeasureText($text, $small, (New-Object System.Drawing.Size(60000, 40)), $flags)
    $bmp = New-Object System.Drawing.Bitmap($sz.Width, 24)
    $g   = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::White)
    [System.Windows.Forms.TextRenderer]::DrawText($g, $text, $small, (New-Object System.Drawing.Point(0, 0)),
        [System.Drawing.Color]::Black, [System.Drawing.Color]::White, $flags)
    $g.Dispose()
    $cols = Get-Cols $bmp 0 $sz.Width 0
    $bmp.Dispose()
    return ,$cols
}

# Title: draw large, crop to the ink, centre vertically in 48 rows; returns 3 lists (row bands) of equal width
function Render-Title([string]$text) {
    $sz  = [System.Windows.Forms.TextRenderer]::MeasureText($text, $big, (New-Object System.Drawing.Size(60000, 200)), $flags)
    $bmp = New-Object System.Drawing.Bitmap(($sz.Width + 8), ($sz.Height + 8))
    $g   = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::White)
    [System.Windows.Forms.TextRenderer]::DrawText($g, $text, $big, (New-Object System.Drawing.Point(4, 4)),
        [System.Drawing.Color]::Black, [System.Drawing.Color]::White, $flags)
    $g.Dispose()
    $x0 = $bmp.Width; $x1 = -1; $y0 = $bmp.Height; $y1 = -1
    for ($y = 0; $y -lt $bmp.Height; $y++) {
        for ($x = 0; $x -lt $bmp.Width; $x++) {
            if ($bmp.GetPixel($x, $y).R -lt 128) {
                if ($x -lt $x0) { $x0 = $x }; if ($x -gt $x1) { $x1 = $x }
                if ($y -lt $y0) { $y0 = $y }; if ($y -gt $y1) { $y1 = $y }
            }
        }
    }
    if ($x1 -lt 0) { Write-Host "ERROR: title '$text' is empty"; exit 1 }
    $h = $y1 - $y0 + 1
    if ($h -gt 48) { Write-Host "WARNING: title is $h rows high, cropped to 48"; $h = 48 }
    $top = $y0 - [int][Math]::Floor((48 - $h) / 2)
    $w = $x1 - $x0 + 1
    $bands = @((Get-Cols $bmp $x0 $w $top), (Get-Cols $bmp $x0 $w ($top + 16)), (Get-Cols $bmp $x0 $w ($top + 32)))
    $bmp.Dispose()
    return ,$bands
}

if (-not (Test-Path $InFile)) { Write-Host "ERROR: $InFile not found"; exit 1 }
$texts = @{}
foreach ($line in [IO.File]::ReadAllLines($InFile, [Text.Encoding]::UTF8)) {
    $t = $line.Trim()
    if ($t -eq '' -or $t.StartsWith('#')) { continue }
    $eq = $t.IndexOf('=')
    if ($eq -lt 1) { Write-Host "WARNING: skipped line: $t"; continue }
    $texts[$t.Substring(0, $eq).Trim().ToUpper()] = $t.Substring($eq + 1).Trim()
}
foreach ($k in @('T_PERSON', 'T_THING', 'T_FOUND', 'F_PERSON', 'F_THING', 'F_FOUND')) {
    if (-not $texts.ContainsKey($k) -or $texts[$k] -eq '') { Write-Host "ERROR: $k missing or empty in page.txt"; exit 1 }
}

$words = New-Object System.Collections.Generic.List[int]
$sb    = New-Object System.Text.StringBuilder
$tt    = @{}
[void]$sb.AppendLine('`timescale 1ns/1ps')
[void]$sb.AppendLine('// -----------------------------------------------------------------------------')
[void]$sb.AppendLine('// AUTO-GENERATED by subtitle/gen_page.ps1 from subtitle/page.txt -- do not edit by hand')
[void]$sb.AppendLine("// generated $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
[void]$sb.AppendLine('// Notice-board page text: one 16-bit word per column, bit 0 = top row.')
$ty = 1
foreach ($k in @('T_PERSON', 'T_THING', 'T_FOUND')) {
    $b = Render-Title $texts[$k]
    $w = $b[0].Count
    if ($w -gt 300) { Write-Host "ERROR: $k is $w px wide, max 300"; exit 1 }
    $s = $words.Count
    foreach ($band in $b) { $words.AddRange([int[]]$band) }
    $tt[$ty] = @($s, $w)
    [void]$sb.AppendLine(("//   type {0} {1,-9} start {2,4}  width {3,3}  {4}" -f $ty, $k, $s, $w, $texts[$k]))
    Write-Host ("{0,-9} {1,3} px  {2}" -f $k, $w, $texts[$k])
    $ty++
}
$d_s = $words.Count
foreach ($ch in '0123456789/'.ToCharArray()) {
    $c = Render-Small ([string]$ch)
    for ($i = 0; $i -lt 8; $i++) { if ($i -lt $c.Count) { $words.Add($c[$i]) } else { $words.Add(0) } }
}
[void]$sb.AppendLine(("//   digits start {0}" -f $d_s))
$ff = @{}
$ty = 1
foreach ($k in @('F_PERSON', 'F_THING', 'F_FOUND')) {
    $f = Render-Small $texts[$k]
    if ($f.Count -gt 600) { Write-Host "WARNING: $k is $($f.Count) px wide, cut to 600"; $f.RemoveRange(600, $f.Count - 600) }
    $s = $words.Count
    $words.AddRange([int[]]$f)
    $x0 = [int][Math]::Floor((640 - $f.Count) / 2)
    $ff[$ty] = @($s, $f.Count, $x0)
    [void]$sb.AppendLine(("//   type {0} {1,-9} start {2,4}  width {3,3}  x0 {4,3}  {5}" -f $ty, $k, $s, $f.Count, $x0, $texts[$k]))
    Write-Host ("{0,-9} {1,3} px  {2}" -f $k, $f.Count, $texts[$k])
    $ty++
}
if ($words.Count -gt $Depth) { Write-Host "ERROR: $($words.Count) columns in total, more than $Depth - shorten the titles / footers"; exit 1 }
[void]$sb.AppendLine("// $($words.Count) of $Depth columns used (two BRAM32K)")
[void]$sb.AppendLine('// -----------------------------------------------------------------------------')
[void]$sb.AppendLine('module page_rom (')
[void]$sb.AppendLine('    input  wire        clk,')
[void]$sb.AppendLine('    input  wire [11:0] raddr,')
[void]$sb.AppendLine('    output reg  [15:0] rdata,')
[void]$sb.AppendLine('    input  wire [1:0]  ty,              // 1 person 2 lost item 3 found item')
[void]$sb.AppendLine('    output reg  [11:0] t_s0,            // title band 0 start; band k = t_s0 + k * t_w')
[void]$sb.AppendLine('    output reg  [8:0]  t_w,')
[void]$sb.AppendLine('    output wire [11:0] d_s,             // digits "0123456789/", 8 columns each')
[void]$sb.AppendLine('    output reg  [11:0] f_s,             // footer of this kind of notice')
[void]$sb.AppendLine('    output reg  [9:0]  f_w,')
[void]$sb.AppendLine('    output reg  [9:0]  f_x0')
[void]$sb.AppendLine(');')
[void]$sb.AppendLine(("    assign d_s  = 12'd{0};" -f $d_s))
[void]$sb.AppendLine("    reg [15:0] mem [0:$($Depth - 1)] /* fehdl force_ram=1, ram_style=""bram_32k"" */;")
[void]$sb.AppendLine('    integer i;')
[void]$sb.AppendLine('    initial begin')
[void]$sb.AppendLine("        for (i = 0; i < $Depth; i = i + 1)")
[void]$sb.AppendLine("            mem[i] = 16'h0000;")
for ($i = 0; $i -lt $words.Count; $i++) {
    if ($words[$i] -ne 0) { [void]$sb.AppendLine(('        mem[{0}] = 16''h{1:X4};' -f $i, $words[$i])) }
}
[void]$sb.AppendLine('    end')
[void]$sb.AppendLine('    always @(posedge clk)')
[void]$sb.AppendLine('        rdata <= mem[raddr];')
[void]$sb.AppendLine('    always @(*) begin')
[void]$sb.AppendLine('        case (ty)')
for ($ty = 1; $ty -le 3; $ty++) {
    [void]$sb.AppendLine(("            2'd{0}: begin t_s0 = 12'd{1}; t_w = 9'd{2}; f_s = 12'd{3}; f_w = 10'd{4}; f_x0 = 10'd{5}; end" -f
        $ty, $tt[$ty][0], $tt[$ty][1], $ff[$ty][0], $ff[$ty][1], $ff[$ty][2]))
}
[void]$sb.AppendLine("            default: begin t_s0 = 12'd0; t_w = 9'd0; f_s = 12'd0; f_w = 10'd0; f_x0 = 10'd0; end")
[void]$sb.AppendLine('        endcase')
[void]$sb.AppendLine('    end')
[void]$sb.AppendLine('endmodule')
[IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "OK: wrote $OutFile ($($words.Count) columns)"
